def unit(value: str) -> dict:
    return {"stringUnit": {"state": "translated", "value": value}}


def build_entry(translations: dict[str, str]) -> dict:
    locs = {}
    for locale in LOCALES:
        value = translations.get(locale) or translations.get("en")
        if value is None:
            continue
        locs[locale] = unit(value)
    return {"localizations": locs}


def write_catalog(path: Path, entries: dict[str, dict[str, str]]) -> None:
    data = {
        "sourceLanguage": "en",
        "strings": {key: build_entry(trans) for key, trans in entries.items()},
        "version": "1.0",
    }
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def merge_into_localizable(entries: dict[str, dict[str, str]]) -> int:
    data = json.loads(LOCALIZABLE.read_text(encoding="utf-8"))
    strings = data.setdefault("strings", {})
    updated = 0
    for key, translations in entries.items():
        entry = strings.setdefault(key, {})
        locs = entry.setdefault("localizations", {})
        en_value = translations.get("en", key)
        for locale in LOCALES:
            value = translations.get(locale, en_value)
            current = locs.get(locale, {}).get("stringUnit", {}).get("value")
            if current != value:
                locs[locale] = unit(value)
                updated += 1
    LOCALIZABLE.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return updated


def main() -> int:
    write_catalog(APP_SHORTCUTS, APP_SHORTCUT_PHRASES)
    write_catalog(INFO_PLIST, INFO_PLIST_STRINGS)

    ui = {}
    ui.update(UI_STRINGS)
    ui.update(MORE_UI)
    ui.update(EXAMPLE_PHRASES)
    ui.update(SIRI_DIALOG_STRINGS)
    # Keep typo key in sync with corrected copy for older builds
    ui["To reminder yourself about a specific title, use Add to Reminders on its detail page."] = UI_STRINGS[
        "To remind yourself about a specific title, use Add to Reminders on its detail page."
    ]
    updated = merge_into_localizable(ui)

    print(f"Wrote {APP_SHORTCUTS.relative_to(ROOT)} ({len(APP_SHORTCUT_PHRASES)} phrases)")
    print(f"Wrote {INFO_PLIST.relative_to(ROOT)} ({len(INFO_PLIST_STRINGS)} keys)")
    print(f"Updated Localizable entries: {updated}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
